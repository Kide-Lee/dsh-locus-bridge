// Bundle the browser model viewer into one ES module.
//
// The DSH client bundle is deliberately dependency-free (only `react` comes
// from the platform module table), so three.js and its loaders cannot live in
// `src/client/plugin.js`. This script produces `lib/model-viewer.js`, which the
// Sidebar fetches with a dynamic import only when a `.fbx` / `.glb` is opened.
//
// Usage: node scripts/build-model-viewer.mjs [--check]
//   --check  fail when lib/model-viewer.js is out of date instead of writing it.

import { build } from 'esbuild'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = join(ROOT, 'src', 'model-viewer', 'viewer.js')
const TARGET = join(ROOT, 'lib', 'model-viewer.js')
const BANNER = [
  '// dsh-locus-bridge — browser 3D model viewer.',
  '//',
  '// Generated by scripts/build-model-viewer.mjs from src/model-viewer/viewer.js.',
  '// Do not edit: edit the source and rebuild (npm run build:viewer).',
  '',
].join('\n')

/** Build the bundle text without writing it. */
export async function renderViewerBundle() {
  const result = await build({
    entryPoints: [SOURCE],
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'browser',
    target: ['chrome100', 'firefox100', 'safari15'],
    minify: true,
    legalComments: 'none',
    logLevel: 'silent',
  })
  const output = result.outputFiles?.[0]
  if (!output) throw new Error('esbuild produced no output for the model viewer.')
  return BANNER + output.text
}

async function main() {
  const check = process.argv.includes('--check')
  const bundle = await renderViewerBundle()
  if (check) {
    const current = existsSync(TARGET) ? readFileSync(TARGET, 'utf8') : ''
    if (current !== bundle) {
      console.error('lib/model-viewer.js is out of date; run `npm run build:viewer`.')
      process.exitCode = 1
      return
    }
    console.log('model viewer bundle: up to date')
    return
  }
  mkdirSync(dirname(TARGET), { recursive: true })
  writeFileSync(TARGET, bundle)
  console.log(`model viewer bundle: wrote ${TARGET} (${bundle.length} bytes)`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await main()
}
