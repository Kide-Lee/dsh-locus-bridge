// Wrap `src/client/plugin.js` into the client bundle DSH loads.
//
// DSH's client module system executes a bundle that calls
// `window.__ModuleLoader__.load({ id, factory })`; the factory receives a
// `require` that resolves the platform module table. The source file is plain
// ESM so tests can import it directly, so this script does the one mechanical
// translation a bundler would otherwise do:
//
//   * drop the `export` keyword from declarations (the bundle exports nothing),
//   * wrap the body in the factory closure,
//   * install `require('react')` from the module table the factory receives.
//
// Usage: node scripts/build-client.mjs [--check]
//   --check  fail when lib/client.js is out of date instead of writing it.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = join(ROOT, 'src', 'client', 'plugin.js')
const TARGET = join(ROOT, 'lib', 'client.js')
const PACKAGE = join(ROOT, 'package.json')

/** Strip ESM syntax a `__ModuleLoader__` factory body cannot contain. */
export function toFactoryBody(source) {
  let body = source
  // `export const/function/class/let` -> plain declarations.
  body = body.replace(/^export\s+(async\s+function|function|const|let|var|class)\b/gm, '$1')
  // A trailing `export { name, ... }` block is redundant inside a factory.
  body = body.replace(/^export\s*\{[^}]*\}\s*;?\s*$/gm, '')
  if (/^\s*(?:import|export)\s/m.test(body)) {
    throw new Error('plugin.js still contains ESM import/export syntax after stripping; keep the client source dependency-free.')
  }
  // `import.meta` has no meaning inside a factory either.
  if (/\bimport\.meta\b/.test(body)) {
    throw new Error('plugin.js must not use import.meta.')
  }
  return body
}

/** The complete bundle text. */
export function renderBundle(source) {
  const packageJson = JSON.parse(readFileSync(PACKAGE, 'utf8'))
  const id = packageJson.name
  const body = toFactoryBody(source)
  return [
    '// dsh-locus-bridge — browser half.',
    '//',
    '// Generated by scripts/build-client.mjs from src/client/plugin.js.',
    '// Do not edit: edit the source and rebuild (npm run build:client).',
    '//',
    '// The bundle only registers a factory; every side effect (styles, tab',
    '// registration) runs when DSH materializes the module.',
    'window.__ModuleLoader__.load({',
    `  id: ${JSON.stringify(id)},`,
    '  factory: (require) => {',
    '    var module = { exports: {} };',
    '    var exports = module.exports;',
    '    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });',
    '',
    body,
    '',
    '    var plugin = createLocusAssetPlugin(require);',
    '    exports.createLocusAssetPlugin = createLocusAssetPlugin;',
    '    exports.TAB_ID = TAB_ID;',
    '    exports.TAB_KIND = TAB_KIND;',
    '    exports.EXTENSIONS = EXTENSIONS;',
    '    exports.inject = plugin.inject;',
    '    exports.apply = plugin.apply;',
    '    return module.exports;',
    '  },',
    '});',
    '',
  ].join('\n')
}

function main() {
  const check = process.argv.includes('--check')
  const source = readFileSync(SOURCE, 'utf8')
  const bundle = renderBundle(source)
  if (check) {
    const current = existsSync(TARGET) ? readFileSync(TARGET, 'utf8') : ''
    if (current !== bundle) {
      console.error('lib/client.js is out of date; run `npm run build:client`.')
      process.exitCode = 1
      return
    }
    console.log('client bundle: up to date')
    return
  }
  mkdirSync(dirname(TARGET), { recursive: true })
  writeFileSync(TARGET, bundle)
  console.log(`client bundle: wrote ${TARGET} (${bundle.length} bytes)`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main()
