// Registering the downloaded Unity analyzers with the Roslyn server.
//
// Unity's generated csproj only lists the analyzers whatever IDE last wrote
// them, so the `Microsoft.Unity.Analyzers` package the bridge downloads never
// loads and `UNT*` diagnostics never appear. Upstream Locus solves this by
// writing a marker-tagged `Directory.Build.props` next to the solution
// (`csharp_lsp/mod.rs::write_analyzer_props`): MSBuild walks up from each
// generated csproj, so one file adds the `<Analyzer>` item to every project of
// the set, and removing the file takes it back out. This module is the same
// file, with the same marker and the same guarantees:
//
//   * a file without the marker belongs to the user and is never overwritten
//     or deleted (`writeAnalyzerProps` refuses, `removeAnalyzerProps` leaves it);
//   * the file is removed when the workspace is disposed (idle reaper, `force`
//     reload, pool shutdown), so a closed bridge leaves the checkout as it
//     found it;
//   * content only changes when it differs, so a reload does not rewrite a
//     file the editor may be scanning.
//
// Unity's own compilation ignores `Directory.Build.props`; only MSBuild-based
// IDE and language-server loads read it.
//
// This is the only path that works. Appending a synthetic `<ItemGroup>` to the
// project text a client opens does not: the server's MSBuild host evaluates a
// project from disk, so the item never reaches evaluation (measured on Unity
// 2022.3 + Roslyn 5.4.0 — no `UNT*` diagnostic). With this file in place the
// same server reports them (`Awake()` left empty → `UNT0001`).

import { readFileSync, statSync, unlinkSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

import { unityAnalyzersDir } from './assets.js'

export const UNITY_ANALYZER_FILE = 'Microsoft.Unity.Analyzers.dll'
/** Marks the props file as ours; same string as upstream. */
export const ANALYZER_PROPS_MARKER = 'locus:unity-analyzers'
export const ANALYZER_PROPS_FILE = 'Directory.Build.props'

/** The analyzer assembly path, or `null` when the download is not present. */
export function unityAnalyzerPath(env = process.env) {
  const path = join(unityAnalyzersDir(env), UNITY_ANALYZER_FILE)
  try {
    return statSync(path).isFile() ? path : null
  } catch {
    return null
  }
}

/** Path of the props file for a workspace root. */
export function analyzerPropsPath(root) {
  return join(root, ANALYZER_PROPS_FILE)
}

/** The props file's exact content for `dll`. */
export function analyzerPropsContent(dll) {
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<Project>',
    `  <!-- ${ANALYZER_PROPS_MARKER} : generated by dsh-locus-bridge while its C# code analysis feature runs.`,
    '       Adds Microsoft.Unity.Analyzers (UNT* diagnostics) to IDE / language-server',
    "       loads of the Unity-generated projects. Unity's own compilation ignores",
    '       this file. Safe to delete; the bridge recreates it while the feature is on. -->',
    '  <ItemGroup>',
    `    <Analyzer Include="${escapeXml(dll)}" />`,
    '  </ItemGroup>',
    '</Project>',
    '',
  ].join('\n')
}

function escapeXml(value) {
  return String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('"', '&quot;')
}

/**
 * Write (or refresh) the props file for `root`.
 *
 * @returns {{ ok: true, path: string } | { ok: false, reason: string }}
 */
export function writeAnalyzerProps(root, dll) {
  const path = analyzerPropsPath(root)
  let existing = null
  try {
    existing = readFileSync(path, 'utf8')
  } catch {
    // Absent (or unreadable): treat as absent; the write below reports a real
    // failure.
  }
  if (existing !== null && !existing.includes(ANALYZER_PROPS_MARKER)) {
    return { ok: false, reason: `${path} already exists and was not created by dsh-locus-bridge` }
  }
  const content = analyzerPropsContent(dll)
  if (existing === content) return { ok: true, path }
  try {
    writeFileSync(path, content)
  } catch (error) {
    return { ok: false, reason: `failed to write ${path}: ${error.message}` }
  }
  return { ok: true, path }
}

/** Remove the marker-tagged props file; a user-owned file is left alone. */
export function removeAnalyzerProps(root) {
  const path = analyzerPropsPath(root)
  let existing
  try {
    existing = readFileSync(path, 'utf8')
  } catch {
    return false
  }
  if (!existing.includes(ANALYZER_PROPS_MARKER)) return false
  try {
    unlinkSync(path)
    return true
  } catch {
    return false
  }
}