// Which `.cs` files the connected editor has told us about.
//
// Upstream reloads its workspace when the project files stop describing the
// code on disk, and it decides that per query: the editor pushes every source
// file it knows about, and one that no project claims means the generated
// `.sln` predates the file. This module is the same decision, applied to the
// files the Unity editor's `code_*` answers have already named — `code_hover`
// and friends return absolute paths, `code_symbol_search` returns locations —
// because this plugin has no editor-side push channel.
//
// With `project-references` enabled `projectFilesStale` already notices a
// source file newer than the project files. That check needs the file to exist
// when the query runs; this one needs the file to have been *mentioned* once,
// which also catches a file written before the project files but never added
// to them (a csproj generated by an IDE that did not see it yet).

const MAX_TRACKED = 20_000

/** workspace root → Set of absolute `.cs` paths */
const tracked = new Map()

/** Note that `path` exists in the workspace rooted at `root`. */
export function trackSource(root, path) {
  if (!root || !path) return
  if (!String(path).toLowerCase().endsWith('.cs')) return
  let set = tracked.get(root)
  if (!set) {
    set = new Set()
    tracked.set(root, set)
  }
  if (set.size >= MAX_TRACKED) set.clear()
  set.add(String(path))
}

/** Note every `.cs` path in `paths` (locations, symbol results). */
export function trackSources(root, paths) {
  for (const path of paths ?? []) trackSource(root, path)
}

/** Paths previously seen in `root`, newest insertion last. */
export function trackedSources(root) {
  return [...(tracked.get(root) ?? [])]
}

/**
 * Forget one workspace (its server was closed or its checkout went away), or
 * one file that has since been added to the project files.
 */
export function forgetTrackedSource(root, path) {
  tracked.get(root)?.delete(String(path))
}

/** Forget one workspace (its server was closed or its checkout went away). */
export function forgetTrackedSources(root) {
  tracked.delete(root)
}